#!/usr/bin/env python3
# Writes the page-2 module that reaches page 1, from the page-1 linker map:
#   addresses (RAM variables, constants, jump targets for R_JP1) as global equates, and
#   for each page-1 routine that page 2 calls, a stub of the same name that calls it through R_CALL1.
# Usage: mksyms.py PAGE1.map OUT.s --addr NAME... --call NAME...
# Copyright (C) 2026 Santiago Crespo
# SPDX-License-Identifier: GPL-3.0-or-later
import re
import sys

mapfile, out = sys.argv[1], sys.argv[2]
kinds, kind = {"--addr": [], "--call": []}, None
for a in sys.argv[3:]:
    if a in kinds:
        kind = a
    else:
        kinds[kind].append(a)
syms = {}
for m in re.finditer(r"\b([0-9A-F]{8})\s+([A-Za-z_][A-Za-z0-9_]*)", open(mapfile).read()):
    syms.setdefault(m.group(2), int(m.group(1), 16))
missing = [n for n in kinds["--addr"] + kinds["--call"] if n not in syms]
if missing:
    sys.exit("not in the map: " + " ".join(missing))
with open(out, "w") as f:
    f.write("; Generated by mksyms.py from %s. Do not edit.\n\t.area\tP2\n" % mapfile)
    for n in kinds["--addr"]:
        f.write("%s == 0x%04X\n" % (n, syms[n]))
    for n in kinds["--call"]:
        f.write("\t.globl\t%s\n%s:\tpush\thl\n\tld\thl, #0x%04X\n\tjp\tR_CALL1\n" % (n, n, syms[n]))
